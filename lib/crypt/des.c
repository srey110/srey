// 密钥扩展：每轮 48 位子密钥按 6 位一组拆成 8 组，奇数组进 k[0]、偶数组进 k[1]，排法与 _des_f 的取位一致
static void _des_key_setup(const uint8_t *key, int32_t encrypt, uint32_t schedule[16 * 2]) {
    static const uint32_t key_rnd_shift[16] = { 1,1,2,2,2,2,2,2,1,2,2,2,2,2,2,1 };
    uint32_t c = _crypt_read32le(key), d = _crypt_read32le(key + 4), s, t, i;
    uint32_t *k;
    // PC-1：做完后 c、d 的第 i 位即标准 C[i]、D[i]
    DES_SWAP(d, c, t, 4, 0x0f0f0f0fu);
    DES_HSWAP(c, t, 0xcccc0000u);
    DES_HSWAP(d, t, 0xcccc0000u);
    DES_SWAP(d, c, t, 1, 0x55555555u);
    DES_SWAP(c, d, t, 8, 0x00ff00ffu);
    DES_SWAP(d, c, t, 1, 0x55555555u);
    d = ((d & 0xffu) << 16) | (d & 0xff00u) | ((d & 0xff0000u) >> 16) | ((c & 0xf0000000u) >> 4);
    c &= 0x0fffffffu;
    for (i = 0; i < 16; ++i) {
        // 标准里的循环左移在这种位序下是 28 位内循环右移
        c = ((c >> key_rnd_shift[i]) | (c << (28 - key_rnd_shift[i]))) & 0x0fffffffu;
        d = ((d >> key_rnd_shift[i]) | (d << (28 - key_rnd_shift[i]))) & 0x0fffffffu;
        s = _des_skb[0][c & 0x7f] | _des_skb[1][(c >> 7) & 0x7f] | _des_skb[2][(c >> 14) & 0x7f] | _des_skb[3][c >> 21];
        t = _des_skb[4][d & 0x7f] | _des_skb[5][(d >> 7) & 0x7f] | _des_skb[6][(d >> 14) & 0x7f] | _des_skb[7][d >> 21];
        k = schedule + (encrypt ? i : 15 - i) * 2;
        k[0] = (s & 0xffff0000u) | (t >> 16);
        k[1] = (s << 16) | (t & 0xffffu);
    }
}
// 3DES 的密钥是三段独立的 8 字节子密钥，短密钥不能像单密钥算法那样整体补零：
// K2、K3 同时为零时 E_0(D_0(x)) 是恒等变换，3DES 会塌回单重 DES；K3 单独为零虽不减弱强度，
// 但密文与所有合规实现都对不上。按 NIST SP 800-67 的三种取法补齐——24 字节三段独立，
// 16 字节 K3 取 K1，8 字节三段相同（该取法本身即等价于单重 DES）。非标准长度按低一档补零
static void _des3_padding_key(const char *key, size_t klens, uint8_t pdkey[24]) {
    if (klens >= 24) {
        memcpy(pdkey, key, 24);
        return;
    }
    if (klens > 16) {
        memcpy(pdkey, key, klens);
        ZERO(pdkey + klens, 24 - klens);
        return;
    }
    if (klens > 8) {
        memcpy(pdkey, key, klens);
        ZERO(pdkey + klens, 16 - klens);
    } else {
        if (klens > 0) {
            memcpy(pdkey, key, klens);
        }
        ZERO(pdkey + klens, 8 - klens);
        memcpy(pdkey + 8, pdkey, 8);
    }
    memcpy(pdkey + 16, pdkey, 8);
}
void des_init(des_ctx *des, const char *key, size_t klens, int32_t des3, int32_t encrypt) {
    des->des3 = des3;
    if (des->des3) {
        uint8_t pdkey[24];
        _des3_padding_key(key, klens, pdkey);
        if (encrypt) {
            _des_key_setup(pdkey, encrypt, des->schedule);
            _des_key_setup(pdkey + 8, !encrypt, des->schedule + 16 * 2);
            _des_key_setup(pdkey + 16, encrypt, des->schedule + 2 * 16 * 2);
        } else {
            _des_key_setup(pdkey + 16, encrypt, des->schedule);
            _des_key_setup(pdkey + 8, !encrypt, des->schedule + 16 * 2);
            _des_key_setup(pdkey, encrypt, des->schedule + 2 * 16 * 2);
        }
        secure_zero(pdkey, sizeof(pdkey));
    } else {
        uint8_t pdkey[8];
        uint8_t *k = _padding_key(key, klens, pdkey, 8);
        _des_key_setup(k, encrypt, des->schedule);
        secure_zero(pdkey, sizeof(pdkey));
    }
}
// Feistel 函数 F：R 循环右移 3 位得第 1/3/5/7 组扩展位、循环左移 1 位得第 2/4/6/8 组，各在一个字节的低 6 位
static uint32_t _des_f(uint32_t r, const uint32_t *k) {
    uint32_t u = ROTR32(r, 3) ^ k[0];
    uint32_t t = ROTR32(r, 31) ^ k[1];
    return _des_sp[0][(u >> 24) & 0x3f] ^ _des_sp[2][(u >> 16) & 0x3f] ^
        _des_sp[4][(u >> 8) & 0x3f] ^ _des_sp[6][u & 0x3f] ^
        _des_sp[1][(t >> 24) & 0x3f] ^ _des_sp[3][(t >> 16) & 0x3f] ^
        _des_sp[5][(t >> 8) & 0x3f] ^ _des_sp[7][t & 0x3f];
}
char *des_crypt(des_ctx *des, const void *data) {
    const uint8_t *in = (const uint8_t *)data;
    const uint32_t *k = des->schedule;
    const uint32_t *end = k + (des->des3 ? 3 : 1) * 16 * 2;
    uint32_t l = _crypt_read32be(in), r = _crypt_read32be(in + 4), t, i;
    // 初始置换 IP
    DES_SWAP(l, r, t, 4, 0x0f0f0f0fu);
    DES_SWAP(l, r, t, 16, 0x0000ffffu);
    DES_SWAP(r, l, t, 2, 0x33333333u);
    DES_SWAP(r, l, t, 8, 0x00ff00ffu);
    DES_SWAP(l, r, t, 1, 0x55555555u);
    // 每段 16 轮，段末左右互换；3DES 段与段之间的 FP、IP 互逆，直接省掉
    for (; k < end; k += 16 * 2) {
        for (i = 0; i < 16 * 2; i += 4) {
            l ^= _des_f(r, k + i);
            r ^= _des_f(l, k + i + 2);
        }
        t = l;
        l = r;
        r = t;
    }
    // 逆初始置换 FP，即 IP 的各步倒序
    DES_SWAP(l, r, t, 1, 0x55555555u);
    DES_SWAP(r, l, t, 8, 0x00ff00ffu);
    DES_SWAP(r, l, t, 2, 0x33333333u);
    DES_SWAP(l, r, t, 16, 0x0000ffffu);
    DES_SWAP(l, r, t, 4, 0x0f0f0f0fu);
    _crypt_write32be(des->output, l);
    _crypt_write32be(des->output + 4, r);
    return (char *)des->output;
}
