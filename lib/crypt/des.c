#define ROTR32(x, n) (((x) >> (n)) | ((x) << (32 - (n))))
// 把 a 右移 n 位后与 b 在掩码 m 覆盖的位上互换，t 为临时量；IP / FP 都由它拼成
#define DES_SWAP(a, b, t, n, m) ((t) = (((a) >> (n)) ^ (b)) & (m), (b) ^= (t), (a) ^= (t) << (n))
// a 左移 18 位后与自身在掩码 m 覆盖的位上互换，PC-1 用
#define DES_HSWAP(a, t, m) ((t) = (((a) << 18) ^ (a)) & (m), (a) ^= (t) ^ ((t) >> 18))

