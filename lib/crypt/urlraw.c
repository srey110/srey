char *url_encode(const char *data, const size_t lens, char *out, int32_t space2plus) {
    unsigned char c;
    size_t i;
    unsigned char const *from = (unsigned char *)data;
    unsigned char *to = (unsigned char *)out;
    for (i = 0; i < lens; i++) {
        c = from[i];
        if (urlkeep[c]) {
            *to++ = c;
        } else if (c == ' ' && space2plus) {
            *to++ = '+';
        } else {
            to[0] = '%';
            to[1] = hexchars[c >> 4];
            to[2] = hexchars[c & 15];
            to += 3;
        }
    }
    *to = 0;
    return out;
}
// 不用改写的前缀(没有 '%'、也没有要转空格的 '+')只读不写，读到第一个要解码的字节才开始搬
size_t url_decode(char *data, size_t lens, int32_t plus2space) {
    unsigned char *s = (unsigned char *)data;
    unsigned char c, h, l;
    size_t i = 0, j = 0;
    while (i < lens
        && '%' != s[i]
        && !('+' == s[i] && plus2space)) {
        i++;
    }
    if (i == lens) {
        return lens;
    }
    j = i;
    while (i < lens) {
        c = s[i];
        if ('%' == c
            && lens - i > 2
            && (h = hexval[s[i + 1]]) < 16
            && (l = hexval[s[i + 2]]) < 16) {
            s[j] = (unsigned char)((h << 4) | l);
            i += 3;
        } else {
            s[j] = ('+' == c && plus2space) ? ' ' : c;
            i++;
        }
        j++;
    }
    return j;
}
